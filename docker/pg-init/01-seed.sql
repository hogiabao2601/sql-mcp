-- PostgreSQL port of mysql-init/01..04 for the conformance suite. TEST-ONLY credentials.
-- MySQL databases become SCHEMAS of one database `app`: shop, analytics, "odd-names".
-- Same formulas as the MySQL seed, so the same questions have the same answers (40 orders, 90 items,
-- totals 2279.25); dates are relative to the first start, like the MySQL seed.

CREATE SCHEMA shop;
CREATE SCHEMA analytics;
CREATE SCHEMA "odd-names";

CREATE TABLE shop.customers (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       varchar(60)  NOT NULL,
  email      varchar(120) NOT NULL,
  city       varchar(60)  NOT NULL,
  created_at timestamp    NOT NULL
);
CREATE TABLE shop.products (
  id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name     varchar(80)   NOT NULL,
  category varchar(40)   NOT NULL,
  price    numeric(10,2) NOT NULL
);
CREATE TABLE shop.orders (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer       NOT NULL REFERENCES shop.customers(id),
  status      varchar(10)   NOT NULL CHECK (status IN ('paid', 'shipped', 'cancelled')),
  total       numeric(10,2) NOT NULL DEFAULT 0,
  created_at  timestamp     NOT NULL
);
CREATE TABLE shop.order_items (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   integer       NOT NULL REFERENCES shop.orders(id),
  product_id integer       NOT NULL REFERENCES shop.products(id),
  quantity   integer       NOT NULL,
  unit_price numeric(10,2) NOT NULL
);
CREATE INDEX order_items_order_id ON shop.order_items (order_id);
CREATE INDEX order_items_product_id ON shop.order_items (product_id);

