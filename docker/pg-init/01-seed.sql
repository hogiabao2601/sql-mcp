INSERT INTO shop.order_items (order_id, product_id, quantity, unit_price)
SELECT o.id, p.id, 1 + ((o.id + k.k) % 3), p.price
FROM shop.orders o
JOIN (VALUES (1), (2), (3)) AS k(k) ON (o.id + k.k) % 4 <> 0
JOIN shop.products p ON p.id = 1 + ((o.id + k.k * 3) % 8)
ORDER BY o.id, k.k;

UPDATE shop.orders o SET total = x.t
FROM (SELECT order_id, SUM(quantity * unit_price) AS t FROM shop.order_items GROUP BY order_id) x
WHERE x.order_id = o.id;

CREATE TABLE analytics.app_users (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
