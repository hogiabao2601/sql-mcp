GRANT USAGE ON SCHEMA shop, analytics, "odd-names" TO readonly_user;
GRANT SELECT ON ALL TABLES IN SCHEMA shop, analytics, "odd-names" TO readonly_user;
CREATE ROLE app_writer LOGIN PASSWORD 'writer-pw-test-only';
GRANT USAGE ON SCHEMA shop TO app_writer;
